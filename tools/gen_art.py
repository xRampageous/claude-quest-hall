"""Build hooks/art.ts for the task-board mod from its assets/ folder.

usage: python gen_art.py <mod dir>

Characters: assets/<name>.png for each name in CAST, 5 frames side by side
(idle, typing A, typing B, reading A, reading B), cleaned by fix_sheet.py.
Scenery: assets/workbench-art.json. Every sprite becomes compact SVG paths,
one per color, so a scene of rooms and characters stays small.
"""
import base64
import io
import json
import sys
from PIL import Image

mod = sys.argv[1]
assets = f"{mod}/assets"


def paths(img, skip=None):
    """One <path> per color. Each horizontal run of a color is a rectangle, and
    the same run on the rows below joins it, so flat areas cost one rectangle.
    A filled path needs no closing `z`."""
    w, h = img.size
    px = img.load()
    open_rects = {}  # (color, x0, x1) -> (y0, height)
    rects = {}
    for y in range(h + 1):
        row = set()
        x = 0
        while y < h and x < w:
            c = px[x, y]
            if c[3] < 128 or (skip and skip(c)):
                x += 1
                continue
            x0 = x
            while x < w and px[x, y] == c:
                x += 1
            row.add(("#%02x%02x%02x" % c[:3], x0, x))
        for key in list(open_rects):
            if key in row:
                y0, n = open_rects[key]
                open_rects[key] = (y0, n + 1)
                row.discard(key)
            else:
                y0, n = open_rects.pop(key)
                color, x0, x1 = key
                rects.setdefault(color, []).append(f"M{x0} {y0}h{x1 - x0}v{n}h{x0 - x1}")
        for key in row:
            open_rects[key] = (y, 1)
    return "".join(f'<path fill="{c}" d="{"".join(d)}"/>' for c, d in rects.items())


def png64(img):
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def grid(sprite, only=None, without=None):
    img = Image.new("RGBA", (sprite["w"], sprite["h"]))
    for y, row in enumerate(sprite["rows"]):
        for x, ch in enumerate(row):
            if ch == "." or ch not in sprite["palette"] or (only and ch != only) or (without and ch == without):
                continue
            hexc = sprite["palette"][ch].lstrip("#")
            img.putpixel((x, y), tuple(int(hexc[i:i + 2], 16) for i in (0, 2, 4)) + (255,))
    return img


# Claude is the wizard; subagents take the rest in turn.
CAST = ["wizard", "knight", "ranger", "smith"]
chars = []
for name in CAST:
    sheet = Image.open(f"{assets}/{name}.png").convert("RGBA")
    fw = sheet.width // 5
    chars.append([sheet.crop((i * fw, 0, i * fw + fw, sheet.height)) for i in range(5)])

art = json.load(open(f"{assets}/workbench-art.json", encoding="utf8"))
fur = art["furniture"]
mon = fur["monitorOn"]


def sprite(img_or_spec, inner=None):
    if isinstance(img_or_spec, Image.Image):
        return {"w": img_or_spec.width, "h": img_or_spec.height, "svg": inner if inner is not None else paths(img_or_spec)}
    return {"w": img_or_spec["w"], "h": img_or_spec["h"], "svg": paths(grid(img_or_spec))}


# The glow of the lit monitor is drawn apart, in the agent's own color.
glow = grid(mon, only="S")
glow_d = paths(glow).replace('fill="', 'data-x="')
out = {
    "characters": [{"w": f[0].width, "h": f[0].height, "frames": [paths(x) for x in f]} for f in chars],
    "pngs": [[png64(x) for x in f] for f in chars],
    "desk": sprite(fur["desk"]),
    "monitor": {"w": mon["w"], "h": mon["h"], "svg": paths(grid(mon, without="S")),
                "glow": "".join(p.split(' d="')[1].rstrip('"/>') for p in paths(glow).split("<path")[1:])},
    "plant": sprite(fur["plant"]),
    "chair": sprite(fur["chair"]),
    "rooms": [{"name": r["name"], "accent": r["accent"], "floor": sprite(r["floorTile"]), "wall": sprite(r["wallStrip"])} for r in art["rooms"]],
    "icons": {k: sprite(v) for k, v in art["icons"].items()},
}

ts = [
    "// Generated by gen_art.py from assets/: do not edit by hand.",
    "// All of it is original art made for this mod: the wizard (Claude), the knight,",
    "// ranger and smith (subagents, in turn), and the scenery.",
    "export type Sprite = { w: number; h: number; svg: string }",
    "export type Character = { w: number; h: number; frames: readonly string[] }",
    "export type Room = { name: string; accent: string; floor: Sprite; wall: Sprite }",
    "",
    "// Frames: idle, typing A, typing B, reading A, reading B; each frame is SVG paths.",
    f"export const CHARACTERS: readonly Character[] = {json.dumps(out['characters'])}",
    "// The same frames as base64 PNGs, for the terminal's Image.",
    f"export const CHARACTER_PNGS: readonly (readonly string[])[] = {json.dumps(out['pngs'])}",
    f"export const DESK: Sprite = {json.dumps(out['desk'])}",
    "// `glow` is the path data of the lit pixels, filled with the working agent's color.",
    f"export const MONITOR: Sprite & {{ glow: string }} = {json.dumps(out['monitor'])}",
    f"export const PLANT: Sprite = {json.dumps(out['plant'])}",
    f"export const CHAIR: Sprite = {json.dumps(out['chair'])}",
    f"export const ROOMS: readonly Room[] = {json.dumps(out['rooms'])}",
    f"export const ICONS: Readonly<Record<'stuck' | 'idle' | 'coins' | 'xp', Sprite>> = {json.dumps(out['icons'])}",
    "",
    "// A whole SVG document of one sprite or frame, for an Svg element on its own.",
    "export function svgOf(w: number, h: number, inner: string): string {",
    "  return `<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 ${w} ${h}\" shape-rendering=\"crispEdges\">${inner}</svg>`",
    "}",
    "",
]
open(f"{mod}/hooks/art.ts", "w", encoding="utf8").write("\n".join(ts))
sizes = [len(f) for c in out["characters"] for f in c["frames"]]
print(f"art.ts written; frame svg sizes {min(sizes)}-{max(sizes)} chars")
