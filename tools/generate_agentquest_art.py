#!/usr/bin/env python3
"""Embed the curated Agent Quest PNGs as data URIs for Patchhaven's SVG map.

Each animation becomes one horizontal strip of 56×56 frames, so the live map
can step through every frame by moving a clipped strip instead of embedding a
separate image per frame. Requires Pillow.
"""

from __future__ import annotations

import base64
import io
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "agent-quest"
BACKGROUND_OUTPUT = ROOT / "hooks" / "agentquest-backgrounds.ts"
SPRITE_OUTPUT = ROOT / "hooks" / "agentquest-sprites.ts"
ROLES = ("mage", "ranger", "rogue", "sage")
DIRECTIONS = ("north", "south", "east", "west")
# Bugs that a failing check releases: one for the Terminal, one for elsewhere.
MOBS = ("glitch_pit", "circuit_catacombs")
FRAME = 56
FRAMES = 9


def png_uri(path: Path) -> str:
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def strip_uri(paths: list[Path]) -> str:
    strip = Image.new("RGBA", (FRAME * len(paths), FRAME))
    for index, path in enumerate(paths):
        frame = Image.open(path).convert("RGBA")
        if frame.size != (FRAME, FRAME):
            raise SystemExit(f"Expected a {FRAME}×{FRAME} frame: {path}")
        strip.alpha_composite(frame, (index * FRAME, 0))
    out = io.BytesIO()
    strip.save(out, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(out.getvalue()).decode("ascii")


def frames(folder: Path) -> list[Path]:
    paths = [folder / f"{frame}.png" for frame in range(FRAMES)]
    missing = [path for path in paths if not path.is_file()]
    if missing:
        raise SystemExit(f"Missing frames: {', '.join(map(str, missing))}")
    return paths


def main() -> None:
    scenes = {
        path.stem: png_uri(path)
        for path in sorted((ASSETS / "scenes-compact").glob("*.png"))
    }
    if len(scenes) != 16:
        raise SystemExit(f"Expected all 16 Agent Quest scenes, found {len(scenes)}")

    sprites = {}
    for role in ROLES:
        root = ASSETS / "sprites" / role / "t1"
        if not root.is_dir():
            raise SystemExit(f"Missing first-tier sprites for {role}: {root}")
        sprites[role] = {
            "idle": {direction: png_uri(root / "idle" / f"{direction}.png") for direction in DIRECTIONS},
            "walk": {direction: strip_uri(frames(root / "walk" / direction)) for direction in DIRECTIONS},
            "attack": strip_uri(frames(root / "attack")),
        }
    mobs = {name: strip_uri(frames(ASSETS / "sprites" / "monsters" / name / "idle")) for name in MOBS}

    guild = png_uri(ASSETS / "overworld" / "guild-compact.png")
    header = "/* Generated by tools/generate_agentquest_art.py. Do not edit directly. */\n"
    background_source = header
    background_source += "export const AGENT_QUEST_SCENES: Readonly<Record<string, string>> = " + json.dumps(scenes, separators=(",", ":")) + "\n"
    background_source += "export const AGENT_QUEST_GUILD = " + json.dumps(guild) + "\n"
    sprite_source = header
    sprite_source += "export type AgentQuestDirection = 'north' | 'south' | 'east' | 'west'\n"
    sprite_source += f"// Walk, attack and mob animations are strips of {FRAMES} frames, each {FRAME}×{FRAME}.\n"
    sprite_source += f"export const AGENT_QUEST_FRAME = {FRAME}\n"
    sprite_source += f"export const AGENT_QUEST_FRAMES = {FRAMES}\n"
    sprite_source += "export type AgentQuestSprite = { idle: Record<AgentQuestDirection, string>; walk: Record<AgentQuestDirection, string>; attack: string }\n"
    sprite_source += "export const AGENT_QUEST_SPRITES: Readonly<Record<string, AgentQuestSprite>> = " + json.dumps(sprites, separators=(",", ":")) + "\n"
    sprite_source += "export const AGENT_QUEST_MOBS: Readonly<Record<'glitch_pit' | 'circuit_catacombs', string>> = " + json.dumps(mobs, separators=(",", ":")) + "\n"
    BACKGROUND_OUTPUT.write_text(background_source, encoding="utf-8", newline="\n")
    SPRITE_OUTPUT.write_text(sprite_source, encoding="utf-8", newline="\n")
    old_module = ROOT / "hooks" / "agentquest-art.ts"
    if old_module.exists():
        old_module.unlink()
    for path in (BACKGROUND_OUTPUT, SPRITE_OUTPUT):
        print(f"Wrote {path.relative_to(ROOT)} ({path.stat().st_size:,} bytes).")
    for role, sprite in sprites.items():
        print(f"  {role}: walk east {len(sprite['walk']['east']):,} chars, attack {len(sprite['attack']):,} chars")
    for name, uri in mobs.items():
        print(f"  mob {name}: {len(uri):,} chars")


if __name__ == "__main__":
    main()
