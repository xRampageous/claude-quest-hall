#!/usr/bin/env python3
"""Embed the curated Agent Quest PNGs as data URIs for Patchhaven's SVG map."""

from __future__ import annotations

import base64
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "agent-quest"
BACKGROUND_OUTPUT = ROOT / "hooks" / "agentquest-backgrounds.ts"
SPRITE_OUTPUT = ROOT / "hooks" / "agentquest-sprites.ts"
ROLES = ("mage", "ranger", "rogue", "sage")
DIRECTIONS = ("north", "south", "east", "west")


def png_uri(path: Path) -> str:
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def main() -> None:
    scenes = {
        path.stem: png_uri(path)
        for path in sorted((ASSETS / "scenes-compact").glob("*.png"))
    }
    if len(scenes) != 16:
        raise SystemExit(f"Expected all 16 Agent Quest scenes, found {len(scenes)}")

    sprites = {}
    for role in ROLES:
        root = ASSETS / "sprites" / role / "t1"
        if not root.is_dir():
            raise SystemExit(f"Missing first-tier sprites for {role}: {root}")
        idle = {direction: png_uri(root / "idle" / f"{direction}.png") for direction in DIRECTIONS}
        walk = {
            direction: [png_uri(root / "walk" / direction / f"{frame}.png") for frame in range(9)]
            for direction in DIRECTIONS
        }
        attack = [png_uri(root / "attack" / f"{frame}.png") for frame in range(9)]
        expected = 4 + 36 + 9
        if len(idle) + sum(map(len, walk.values())) + len(attack) != expected:
            raise SystemExit(f"Incomplete first-tier sprite set for {role}")
        sprites[role] = {"idle": idle, "walk": walk, "attack": attack}

    guild = png_uri(ASSETS / "overworld" / "guild-compact.png")
    header = "/* Generated by tools/generate_agentquest_art.py. Do not edit directly. */\n"
    background_source = header
    background_source += "export const AGENT_QUEST_SCENES: Readonly<Record<string, string>> = " + json.dumps(scenes, separators=(",", ":")) + "\n"
    background_source += "export const AGENT_QUEST_GUILD = " + json.dumps(guild) + "\n"
    sprite_source = header
    sprite_source += "export type AgentQuestDirection = 'north' | 'south' | 'east' | 'west'\n"
    sprite_source += "export type AgentQuestSprite = { idle: Record<AgentQuestDirection, string>; walk: Record<AgentQuestDirection, readonly string[]>; attack: readonly string[] }\n"
    sprite_source += "export const AGENT_QUEST_SPRITES: Readonly<Record<string, AgentQuestSprite>> = " + json.dumps(sprites, separators=(",", ":")) + "\n"
    BACKGROUND_OUTPUT.write_text(background_source, encoding="utf-8", newline="\n")
    SPRITE_OUTPUT.write_text(sprite_source, encoding="utf-8", newline="\n")
    old_module = ROOT / "hooks" / "agentquest-art.ts"
    if old_module.exists():
        old_module.unlink()
    for path in (BACKGROUND_OUTPUT, SPRITE_OUTPUT):
        print(f"Wrote {path.relative_to(ROOT)} ({path.stat().st_size:,} bytes).")


if __name__ == "__main__":
    main()
